// Función helper para obtener indicadores de un output en un año específico
export const getIndicadoresPorOutputYAño = (codOutput, año) => {
  const output = indicadoresPorOutput[codOutput]
  if (!output) return []
  
  // Asegurar que el año sea un número
  const añoNum = typeof año === 'string' ? parseInt(año, 10) : año
  
  return output.indicadores.map(ind => ({
    ...ind,
    resultado: ind.años[añoNum] !== undefined ? ind.años[añoNum] : null
  }))
}

// Función para obtener resumen de un output por año
export const getResumenOutput = (codOutput, año) => {
  // Asegurar que el año sea un número
  const añoNum = typeof año === 'string' ? parseInt(año, 10) : año
  const indicadores = getIndicadoresPorOutputYAño(codOutput, añoNum)
  const totalIndicadores = indicadores.length
  const indicadoresConResultado = indicadores.filter(ind => ind.resultado !== null && ind.resultado !== undefined).length
  
  return {
    totalIndicadores,
    indicadoresConResultado,
    porcentaje: totalIndicadores > 0 ? Math.round((indicadoresConResultado / totalIndicadores) * 100) : 0
  }
}

